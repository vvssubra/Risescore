/** Reviewed Bahasa Malaysia question wording goes here: { f_r1: { text, tip, options: { comfortable: '…' } } } */
export const QUESTION_MS: Record<string, { text?: string; tip?: string; options?: Record<string, string> }> = {};

const dicts: Record<Locale, Dict> = { en, ms };
let locale: Locale = 'en';

export function getLocale(): Locale { return locale; }
export function setLocale(l: Locale) {
  locale = l;
  document.documentElement.lang = l === 'ms' ? 'ms' : 'en';
  try { localStorage.setItem('rise_locale', l); } catch { /* storage may be unavailable */ }
}
export function initLocale() {
  let saved: string | null = null;
  try { saved = localStorage.getItem('rise_locale'); } catch { /* ignore */ }
  const nav = (navigator.languages?.[0] ?? navigator.language ?? 'en').toLowerCase();
  setLocale(saved === 'ms' || saved === 'en' ? saved : nav.startsWith('ms') ? 'ms' : 'en');
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const s = dicts[locale][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export function qText(q: { id: string; text: string; tip: string }) {
  const m = locale === 'ms' ? QUESTION_MS[q.id] : undefined;
  return { text: m?.text ?? q.text, tip: m?.tip ?? q.tip };
}
export function optLabel(qid: string, key: string, fallback: string) {
  return (locale === 'ms' && QUESTION_MS[qid]?.options?.[key]) || fallback;
}
